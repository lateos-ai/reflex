"""Optional compliance records for the Runpod Hub worker (COMPLIANCE, AUDIT_LOG).

Host-side only, like the rest of handler.py: the engine and reflex-openai-adapter are
unchanged, and nothing here runs unless COMPLIANCE or AUDIT_LOG is on.

- COMPLIANCE=on: at worker start the served model is described once (file name,
  sha256, the GGUF's own general.* metadata from `reflex model-info`, and its
  license from models.json), checked against models.json's expected sha256, and
  cached with the engine version, image digest and GPU name. Every job's response
  then carries that description plus the job's own usage and wall time (the
  "attestation"), and a {"compliance": "report"} job returns the image's compliance
  bundle (SBOMs, third-party licenses, package lists) with a filled-in model card.
- AUDIT_LOG=stdout|volume: one JSON line per job, to stdout (Runpod's log stream) or
  appended to one file per worker on the network volume. AUDIT_LOG_CONTENT decides
  whether the prompt and output are left out (off), recorded as sha256 (hash) or
  recorded as sent (full). There is no rotation, retention, shipping or querying:
  those are the deployer's job.

A model's sha256 is computed while it downloads (handler._download feeds
download_hash), or at image build for the baked model, and kept next to the file as
<file>.sha256, so a later worker start reads 64 bytes instead of hashing gigabytes.
A cached model with no .sha256 yet is hashed once.

Everything that runs a process is passed in (run), so the module can be tested
without a GPU (see test_compliance.py).
"""

import datetime
import hashlib
import json
import os
import re
import socket
import subprocess

BUNDLE_DIR = "/usr/share/reflex/compliance"
MODELS_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models.json")
AUDIT_MODES = ("off", "stdout", "volume")
CONTENT_MODES = ("off", "hash", "full")
AUDIT_SUBDIR = "reflex-audit"
USER_SUPPLIED = "unknown (user-supplied)"
NOT_LISTED = "unknown (not in models.json)"
HASH_CHUNK = 8 << 20
SCHEMA = "reflex.compliance/1"
AUDIT_SCHEMA = "reflex.audit/1"

# The general.* keys (from `reflex model-info`) that say where a model came from and
# under what terms; the rest (sampling defaults, quantization_version, ...) is left out.
PROVENANCE_PREFIXES = (
    "name",
    "basename",
    "finetune",
    "version",
    "size_label",
    "organization",
    "author",
    "license",
    "source.",
    "url",
    "repo_url",
    "quantized_by",
    "base_model.",
)

NOT_LEGAL_ADVICE = (
    "Generated by the Reflex Hub worker from the model file, models.json and the image's "
    "compliance bundle. It records facts, not conclusions: it is not legal advice, and "
    "the deployer remains responsible for checking each license and obligation."
)


class ComplianceError(Exception):
    """A compliance setting or check failed: the worker stops with this message."""


def env_flag(value):
    return str(value).strip().lower() in ("1", "on", "true", "yes")


def config_from_env(env):
    def choice(key, allowed):
        value = env.get(key, "").strip().lower() or "off"
        if value not in allowed:
            raise ComplianceError(f"{key} must be one of {', '.join(allowed)}, got {value!r}")
        return value

    cfg = {
        "compliance": env_flag(env.get("COMPLIANCE", "off")),
        "audit_log": choice("AUDIT_LOG", AUDIT_MODES),
        "audit_content": choice("AUDIT_LOG_CONTENT", CONTENT_MODES),
    }
    if cfg["audit_content"] != "off" and cfg["audit_log"] == "off":
        raise ComplianceError("AUDIT_LOG_CONTENT needs AUDIT_LOG set to stdout or volume")
    return cfg


def enabled(cfg):
    """Whether any option is on (the worker then needs the model's sha256)."""
    return cfg["compliance"] or cfg["audit_log"] != "off"


# ---- sha256 -------------------------------------------------------------------------


def download_hash(part, have):
    """A sha256 already fed the first `have` bytes of `part`, for a download resumed
    from that offset: the prefix is read back once, then the rest is hashed as it
    arrives."""
    h = hashlib.sha256()
    if have:
        with open(part, "rb") as f:
            left = have
            while left:
                chunk = f.read(min(HASH_CHUNK, left))
                if not chunk:
                    raise ComplianceError(f"{part} is shorter than {have} bytes")
                h.update(chunk)
                left -= len(chunk)
    return h


def sidecar(path):
    return f"{path}.sha256"


def write_sha256(path, digest):
    """Write `<path>.sha256` in sha256sum's format, atomically (workers sharing a
    volume may write it at once). A read-only directory is not an error: the hash is
    then simply recomputed by the next worker that needs it."""
    tmp = f"{sidecar(path)}.{os.getpid()}.tmp"
    try:
        with open(tmp, "w", encoding="ascii") as f:
            f.write(f"{digest}  {os.path.basename(path)}\n")
        os.replace(tmp, sidecar(path))
    except OSError:
        try:
            os.remove(tmp)
        except OSError:
            pass


def read_sha256(path):
    """The digest in `<path>.sha256`, or None if it is missing, malformed or older
    than the file."""
    side = sidecar(path)
    try:
        if os.path.getmtime(side) < os.path.getmtime(path):
            return None
        with open(side, encoding="ascii") as f:
            digest = f.read(64)
    except (OSError, UnicodeDecodeError):
        return None
    return digest if re.fullmatch(r"[0-9a-f]{64}", digest) else None


def file_sha256(path, log):
    """The file's sha256: from its .sha256 file, else computed once and saved."""
    digest = read_sha256(path)
    if digest is not None:
        return digest
    log(f"hashing {path} (once; saved as {sidecar(path)})")
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(HASH_CHUNK)
            if not chunk:
                break
            h.update(chunk)
    digest = h.hexdigest()
    write_sha256(path, digest)
    return digest


# ---- model description --------------------------------------------------------------


def load_models(path=MODELS_FILE):
    with open(path, encoding="utf-8") as f:
        return json.load(f)["models"]


def model_record(model_id, url, models):
    """models.json's entry for the served model, with its license; a GGUF_URL model,
    or a MODEL value the table doesn't list, gets an "unknown" license."""
    if url:
        return {"id": None, "url": url, "license": USER_SUPPLIED}
    entry = models.get(model_id)
    if entry is None:
        return {"id": model_id, "license": NOT_LISTED}
    return dict(entry, id=model_id)


def gguf_info(path, run=subprocess.run):
    """`reflex model-info <path> --json`: the GGUF's general.* metadata. No GPU."""
    proc = run(["reflex", "model-info", path, "--json"], capture_output=True, text=True, timeout=120)
    if proc.returncode != 0:
        raise ComplianceError(f"reflex model-info {path} failed: {proc.stderr.strip()}")
    return json.loads(proc.stdout)


def gpu_name(run=subprocess.run):
    """The GPU's name from nvidia-smi, or None if it can't be read."""
    try:
        proc = run(
            ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    names = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
    return names[0] if proc.returncode == 0 and names else None


def describe_model(path, model_id, url, models, log, run=subprocess.run, check=True):
    """The served file's description. With check, a models.json sha256 that doesn't
    match the file stops the worker."""
    digest = file_sha256(path, log)
    record = model_record(model_id, url, models)
    expected = record.get("sha256")
    if check and expected and digest != expected:
        raise ComplianceError(
            f"{os.path.basename(path)}: sha256 {digest} does not match models.json's {expected} "
            f"for {model_id} (revision {record.get('revision')}): the file on Hugging Face may have "
            "changed; update models.json or turn COMPLIANCE off"
        )
    info = gguf_info(path, run)
    general = info.get("general", {})
    out = {
        "id": record.get("id"),
        "file": os.path.basename(path),
        "sha256": digest,
        "sha256_matches_models_json": (digest == expected) if expected else None,
        "size_bytes": info.get("size_bytes"),
        "architecture": info.get("architecture"),
        "file_type": info.get("file_type_name", info.get("file_type")),
        "gguf_general": {k: v for k, v in general.items() if k.startswith(PROVENANCE_PREFIXES)},
        "license": record["license"],
    }
    for key in ("license_url", "source", "base_model", "revision", "url"):
        if key in record:
            out[key] = record[key]
    return out


def read_build_info(bundle_dir=None):
    bundle_dir = bundle_dir or BUNDLE_DIR
    try:
        with open(os.path.join(bundle_dir, "build.json"), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def static_block(model, env, gpu, build, rag_embed_model=None):
    """The part of every job's attestation that doesn't change between jobs."""
    block = {
        "schema": SCHEMA,
        "model": model,
        "engine": {
            "reflex_engine_crate_version": (build or {}).get("reflex_engine_crate_version"),
            "image_digest": env.get("REFLEX_IMAGE_DIGEST", "").strip() or None,
            "compliance_bundle": build is not None,
        },
        "gpu": gpu,
    }
    if rag_embed_model is not None:
        block["rag_embed_model"] = rag_embed_model
    return block


def rag_sources(rag_info):
    """The distinct documents a RAG answer drew on, in the order first used."""
    seen, sources = set(), []
    for p in (rag_info or {}).get("passages", []):
        key = (p.get("origin"), p.get("doc"))
        if key not in seen:
            seen.add(key)
            sources.append({"origin": p.get("origin"), "doc": p.get("doc")})
    return sources


def job_attestation(static, outcome, wall_ms):
    job = {"endpoint": outcome.get("endpoint"), "wall_time_ms": round(wall_ms, 1)}
    if outcome.get("usage") is not None:
        job["usage"] = outcome["usage"]
    if outcome.get("stream"):
        job["stream_chunks"] = outcome.get("chunks", 0)
    if outcome.get("rag_info") is not None:
        job["rag_sources"] = rag_sources(outcome["rag_info"])
    return dict(static, job=job)


# ---- per-job outcome ----------------------------------------------------------------


def observe(item, outcome):
    """Record what a yielded item says about the job: usage, output text, errors."""
    if not isinstance(item, dict):
        return
    if "error" in item:
        outcome["error"] = item["error"]
        return
    if isinstance(item.get("usage"), dict):
        outcome["usage"] = item["usage"]
    obj = item.get("object")
    if obj == "chat.completion.chunk":
        outcome["chunks"] = outcome.get("chunks", 0) + 1
        for choice in item.get("choices", []):
            text = (choice.get("delta") or {}).get("content")
            if text:
                outcome.setdefault("output_parts", []).append(text)
    elif obj == "chat.completion":
        choices = item.get("choices") or [{}]
        outcome["output"] = (choices[0].get("message") or {}).get("content")
    elif outcome.get("endpoint") == "classify":
        outcome["output"] = {"label": item.get("label"), "labels": item.get("labels")}


def output_of(outcome):
    if "output_parts" in outcome:
        return "".join(outcome["output_parts"])
    return outcome.get("output")


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def sha256_of(value):
    text = value if isinstance(value, str) else _canonical(value)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def utc_now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def audit_record(event, outcome, started_utc, latency_ms, model_sha256, image_digest, content):
    """One audit line. The prompt is the job input as received; the output is the
    answer text for chat, the labels for classify, and never the vectors for
    embeddings."""
    record = {
        "schema": AUDIT_SCHEMA,
        "job_id": event.get("id"),
        "ts": started_utc,
        "endpoint": outcome.get("endpoint"),
        "model_sha256": model_sha256,
        "image_digest": image_digest,
        "status": "error" if "error" in outcome else "ok",
        "latency_ms": round(latency_ms, 1),
    }
    if "error" in outcome:
        record["error_class"] = outcome.get("error_class", "other")
    if outcome.get("usage") is not None:
        record["usage"] = outcome["usage"]
    if outcome.get("stream"):
        record["stream_chunks"] = outcome.get("chunks", 0)
    prompt = event.get("input", {})
    output = output_of(outcome)
    if content == "hash":
        record["prompt_sha256"] = sha256_of(prompt)
        record["output_sha256"] = sha256_of(output) if output is not None else None
    elif content == "full":
        record["prompt"] = prompt
        record["output"] = output
    return record


class AuditLog:
    """Writes one JSON line per job to stdout, or appends it to
    <volume>/reflex-audit/<worker-id>.jsonl (one file per worker, so concurrent
    workers never share a file)."""

    def __init__(self, mode, volume_dir, env, out=None):
        self.mode = mode
        self.out = out
        self.path = None
        if mode == "volume":
            if not os.path.isdir(volume_dir):
                raise ComplianceError(
                    f"AUDIT_LOG=volume needs a network volume at {volume_dir}: attach one or use stdout"
                )
            worker = env.get("RUNPOD_POD_ID", "").strip() or socket.gethostname()
            worker = re.sub(r"[^A-Za-z0-9._-]", "_", worker) or "worker"
            directory = os.path.join(volume_dir, AUDIT_SUBDIR)
            os.makedirs(directory, exist_ok=True)
            self.path = os.path.join(directory, f"{worker}.jsonl")

    def write(self, record):
        line = json.dumps(record, separators=(",", ":"), ensure_ascii=False) + "\n"
        if self.path is None:
            if self.out is None:
                print(line, end="", flush=True)
            else:
                self.out.write(line)
                self.out.flush()
            return
        with open(self.path, "a", encoding="utf-8") as f:
            f.write(line)


# ---- report job ---------------------------------------------------------------------


def model_card(model):
    """A model card in docs/compliance/model-card-template.md's layout, filled from
    what the worker knows; everything it can't know is left for the deployer."""
    general = model.get("gguf_general", {})

    def row(key, value):
        return f"| {key} | {value if value not in (None, '') else '_not stated_'} |"

    lines = [
        f"# Model card: {general.get('name') or model.get('file')}",
        "",
        f"> {NOT_LEGAL_ADVICE}",
        "",
        "## Identity",
        "",
        "| Field | Value |",
        "| --- | --- |",
        row("Hub model id", model.get("id")),
        row("File", model.get("file")),
        row("sha256", model.get("sha256")),
        row("Matches models.json", model.get("sha256_matches_models_json")),
        row("Size (bytes)", model.get("size_bytes")),
        row("Architecture", model.get("architecture")),
        row("Quantization", model.get("file_type")),
        row("Source", model.get("source") or model.get("url")),
        row("Base model", model.get("base_model")),
        row("Revision checked", model.get("revision")),
        "",
        "## License",
        "",
        "| Field | Value |",
        "| --- | --- |",
        row("License (models.json)", model.get("license")),
        row("License URL", model.get("license_url")),
        row("License (GGUF general.license)", general.get("license") or general.get("license.name")),
        "",
        "## Metadata in the GGUF file",
        "",
        "| Key | Value |",
        "| --- | --- |",
    ]
    lines += [row(f"general.{k}", v) for k, v in sorted(general.items())] or ["| _none_ | |"]
    lines += [
        "",
        "## For the deployer to fill in",
        "",
        "- Intended use and users:",
        "- Uses that are out of scope:",
        "- Evaluation you ran, and its results:",
        "- Known limitations and risks for this use:",
        "- Human oversight in your application:",
        "- Contact:",
        "",
    ]
    return "\n".join(lines)


def _read_text(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def report(static, bundle_dir=None):
    """The whole compliance bundle for a {"compliance": "report"} job: the cached
    attestation, a model card, and every file the image's bundle holds (SBOMs parsed
    as JSON, the rest as text). Files the image doesn't have are listed in
    "missing" rather than failing the job."""
    bundle_dir = bundle_dir or BUNDLE_DIR
    out = {
        "object": "compliance.report",
        "notice": NOT_LEGAL_ADVICE,
        "attestation": static,
        "model_card": model_card(static["model"]),
        "files": {},
        "missing": [],
    }
    if "rag_embed_model" in static:
        out["rag_embed_model_card"] = model_card(static["rag_embed_model"])
    expected = (
        "build.json",
        "reflex.cdx.json",
        "reflex-openai-adapter.cdx.json",
        "THIRD_PARTY_LICENSES.html",
        "THIRD_PARTY_LICENSES-adapter.html",
        "pip-freeze.txt",
        "dpkg.txt",
        "data-handling.md",
    )
    present = sorted(os.listdir(bundle_dir)) if os.path.isdir(bundle_dir) else []
    for name in expected:
        if name not in present:
            out["missing"].append(name)
    for name in present:
        path = os.path.join(bundle_dir, name)
        if not os.path.isfile(path):
            continue
        text = _read_text(path)
        if name.endswith(".json"):
            try:
                out["files"][name] = json.loads(text)
                continue
            except ValueError:
                pass
        out["files"][name] = text
    return out
