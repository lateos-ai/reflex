#!/usr/bin/env python3
"""Measure agent-to-agent handoff latency and energy, over warm and cold engines.

Runs an N-hop chain against one warm process, or one fresh process per hop
(the cold targets, below). Each hop's prompt is a shared
system prompt, the next agent role, and the previous hop's output, which stands
in for one agent handing work to the next. Every hop is one request, sent only
after the previous hop's final response arrives, which is the pattern a
multi-agent loop produces. Reports p50/p95 per hop of:

  rtt           client-measured round trip (send request -> final line read)
  first_token   engine: model call start -> first generated token
  model         engine: whole model call
  overhead      rtt - engine time (transport, JSON, process boundary)
  kv_io         engine: reading the imported KV cache file (--reuse-prefix), or
                copying the pinned prefix in VRAM (--pin-prefix)

Targets:
  stdio         spawns `reflex stdio <model>` and talks over its pipes
  uds           spawns `reflex uds <model> <socket>` and connects (Unix only)
  llama-server  an already-running llama.cpp server (`--url`), POST /completion;
                engine time comes from its `timings` block
  cold          every hop is a fresh `reflex generate` process over the whole
                prompt; no cache files
  cold-chain    every hop is a fresh `reflex generate --import-kv <prefix file>
                --max-tokens N <rest of the prompt>` process. One cold
                `reflex generate --export-kv` process writes the system prompt's
                file first (reported as `setup`). The CLI can't import and export
                in one run, so a hop is one process: an export process plus a
                decode process would pay two cold starts and prefill the whole
                prefix anyway.
  cold-warm     per hop, a fresh `reflex generate --export-kv` process prefills
                the system prompt plus the previous note, and a warm
                `reflex stdio` imports that file (`import_kv`) and decodes from
                the role line
  llama-cli     every hop is a fresh llama.cpp completion process (the model
                reloads each hop); --llama-prompt-cache makes it reuse the system
                prompt through llama.cpp's own `--prompt-cache` file. Newer
                llama.cpp builds moved raw completion from `llama-cli` (now a
                chat UI) to `llama-completion`: pass that with --llama-cli
  selftest      runs the output parsers on canned lines; needs no GPU

Cold hops report the process's wall time (spawn to exit), its first token
(Reflex: `process_start_to_first_token_ms`, measured from main(); llama-cli: the
first generated byte on its stdout, from spawn), the KV file read and write
(Reflex's `kv_io_ms`), and the file size. Cold processes write their cache files
to --kv-dir (default /dev/shm when it exists).

Reflex requests set `"timings": true` (src/ipc.rs, IpcTimings). Greedy decoding
everywhere, so runs are comparable.

--energy: measures GPU energy with `reflex-energy` (cargo build --release
--features nvml --bin reflex-energy), which reads NVML's device-wide energy
counter. Cold targets (cold, cold-chain, llama-cli) run every process under it
and report joules per hop, gross and net of the idle baseline it measures before
each process. The counter is device-wide, so warm targets (stdio, uds,
llama-server) and cold-warm bracket the measured hops once and divide by the hop
count. The idle baseline is measured with the warm engine loaded. Run timing and
energy as separate passes: --energy adds an idle wait before every cold process
and drops llama-cli's first-token column.

--reuse-prefix (stdio/uds): before the chain, one request exports the system
prompt's KV cache to a file (`export_kv`), and every hop then sends only the
rest of its prompt with `import_kv` pointing at that file. This is Reflex's
counterpart to llama-server's `--llama-cache-prompt`. --system-prompt-file
swaps in a longer shared prefix, since the saving grows with its size.

--pin-prefix (stdio/uds): the same, but the system prompt's state stays in
VRAM (`pin_prefix`) and every hop resumes from it (`use_pinned`), copying it
device-to-device instead of reading a file.

--json-schema FILE: every hop's output is constrained to the JSON Schema in FILE
(Reflex's `json_schema` request field; llama-server's `json_schema` /completion
field). Adds two rows: the engine's masking time per hop (`mask_ms_total`,
Reflex only) and how many hop outputs parsed as JSON. A hop that runs out of
--max-tokens before its value is complete counts as invalid
(`grammar_dead_end` on Reflex). scripts/relay_handoff_schema.json is a sample.

--json-prompt: appends JSON_NOTE_INSTRUCTION (write the note as compact JSON, with
an example) to the shared system prompt. It doesn't depend on --json-schema, so
a run with the schema and one without can share the same prompt. A small model
asked for a free-text note under a schema tends to fill the string until
--max-tokens runs out.

Usage:
  scripts/agent_relay_bench.py stdio --reflex target/release/reflex --model m.gguf
  scripts/agent_relay_bench.py uds --reflex target/release/reflex --model m.gguf
  scripts/agent_relay_bench.py llama-server --url http://127.0.0.1:8080
  scripts/agent_relay_bench.py cold-chain --model m.gguf --kv-dir /dev/shm
  scripts/agent_relay_bench.py cold-warm --model m.gguf
  scripts/agent_relay_bench.py llama-cli --llama-cli llama-completion --model m.gguf
  scripts/agent_relay_bench.py selftest
  common: [--hops 20] [--warmup 3] [--max-tokens 32] [--carry-chars 400]
          [--system-prompt-file f.txt] [--json-out results.json]
          [--energy [--reflex-energy target/release/reflex-energy]
                    [--energy-idle-ms 2000]]
  stdio/uds: [--reuse-prefix [--kv-dir /dev/shm] | --pin-prefix]
  stdio/uds/llama-server: [--json-schema scripts/relay_handoff_schema.json]
  any target: [--json-prompt]
  llama-cli: [--llama-cli-args "-ngl 99 --no-warmup ..."] [--llama-prompt-cache]

Standard library only, so it runs anywhere Python 3.8+ does.
"""

