ROLE_LINE = "\nYou are the "


def hop_suffix(hop, previous, carry_chars):
    """The part of a hop's prompt after the shared system prompt."""
    role = ROLES[hop % len(ROLES)]
    note = previous[-carry_chars:] if previous else TASK
    return f"Previous note: {note}{ROLE_LINE}{role}. Your note:"


def split_suffix(suffix):
    """Splits a hop suffix after the previous note's line: (note part, role line)."""
    cut = suffix.rindex(ROLE_LINE) + 1
    return suffix[:cut], suffix[cut:]


def run_process(cmd, first_output_after=None):
    """Runs `cmd` to exit. Returns (stdout, stderr, wall_ms, first_output_ms).

    first_output_ms is the time from spawn until stdout grew past
    `first_output_after` bytes (None when not asked for or never reached).
    """
    start = time.perf_counter()
    proc = subprocess.Popen(
        cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE
    )
    err = []
    pump = threading.Thread(target=lambda: err.append(proc.stderr.read()), daemon=True)
    pump.start()
    out = bytearray()
    first = None
    while True:
        chunk = os.read(proc.stdout.fileno(), 65536)
        if not chunk:
            break
        out += chunk
        if first is None and first_output_after is not None and len(out) > first_output_after:
            first = (time.perf_counter() - start) * 1000.0
    code = proc.wait()
    wall = (time.perf_counter() - start) * 1000.0
    pump.join()
    stdout = out.decode("utf-8", "replace")
    stderr = (err[0] if err else b"").decode("utf-8", "replace")
    if code != 0:
        raise RuntimeError(
            f"{cmd[0]} exited with {code}:\n{stderr[-2000:]}\n{stdout[-2000:]}"
        )
    return stdout, stderr, wall, first


NUMBER_FIELD = re.compile(r"(?:^| )(\w+)=(-?[0-9][0-9.e+-]*)(?= |$)")
RUST_ESCAPE = re.compile(r"\\(u\{[0-9a-fA-F]+\}|.)")
SIMPLE_ESCAPES = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}


def rust_unescape(body):
    """Undoes Rust's `{:?}` string escaping (the body between the quotes)."""

    def one(m):
        esc = m.group(1)
        if esc.startswith("u{"):
            return chr(int(esc[2:-1], 16))
        return SIMPLE_ESCAPES.get(esc, esc)

    return RUST_ESCAPE.sub(one, body)


def find_line(text, marker):
    for line in text.splitlines():
        if line.startswith(marker):
            return line
    return None


def parse_reflex_generate(stdout):
    """The REFLEX_GENERATE_OK line's numeric fields, plus `token_text`."""
    line = find_line(stdout, "REFLEX_GENERATE_OK ")
    if line is None:
        raise RuntimeError(f"no REFLEX_GENERATE_OK line in:\n{stdout[-2000:]}")
    m = re.search(r' token_text="((?:[^"\\]|\\.)*)"', line)
    text = rust_unescape(m.group(1)) if m else ""
    # Numeric fields only, read with token_text cut out, so text can't fake one.
    rest = line if m is None else line[: m.start()] + line[m.end() :]
    fields = {k: float(v) for k, v in NUMBER_FIELD.findall(rest)}
    return fields, text


def parse_energy(stdout):
    """reflex-energy's REFLEX_ENERGY_OK line, in joules."""
    line = find_line(stdout, "REFLEX_ENERGY_OK ")
    if line is None:
        raise RuntimeError(f"no REFLEX_ENERGY_OK line in:\n{stdout[-2000:]}")
    f = {k: float(v) for k, v in NUMBER_FIELD.findall(line)}
    return {
        "wall_ms": f["wall_ms"],
        "energy_j": f["energy_mj"] / 1000.0,
        "idle_baseline_j": f["idle_baseline_mj"] / 1000.0,
        "energy_net_j": f["net_energy_mj"] / 1000.0,
        "idle_power_w": f["idle_power_mw"] / 1000.0,
    }


LLAMA_PERF = {
    "load_ms": re.compile(r"\bload time =\s*([0-9.]+) ms"),
    "prompt_eval_ms": re.compile(r"prompt eval time =\s*([0-9.]+) ms"),
    "prompt_tokens": re.compile(r"prompt eval time =\s*[0-9.]+ ms /\s*([0-9]+) tokens"),
    "eval_ms": re.compile(r"\beval time =\s*([0-9.]+) ms /\s*[0-9]+ runs"),
    "eval_runs": re.compile(r"\beval time =\s*[0-9.]+ ms /\s*([0-9]+) runs"),
}


def parse_llama_perf(stderr):
    """llama.cpp's llama_perf_context_print block (the last one printed)."""
    out = {}
    for key, pat in LLAMA_PERF.items():
        found = pat.findall(stderr)
        if found:
            out[key] = float(found[-1])
    return out


def llama_cli_text(stdout, prompt):
    """llama-cli echoes the prompt, then prints the continuation."""
    text = stdout[len(prompt) :] if stdout.startswith(prompt) else stdout
    return text.replace("[end of text]", "").rstrip("\n")


BRACKET_CHILD = (
    "import sys; print('REFLEX_RELAY_BRACKET_START', flush=True); sys.stdin.read()"
)


class EnergyBracket:
    """Runs reflex-energy around a child that lives until stop() closes its stdin,
    so the device-wide counter brackets whatever the bench does in between."""

    def __init__(self, reflex_energy, idle_ms):
        cmd = [reflex_energy, "--idle-ms", str(idle_ms), "--", sys.executable, "-c", BRACKET_CHILD]
        self.proc = subprocess.Popen(
            cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE
        )
        line = self.proc.stdout.readline().decode("utf-8", "replace")
        if "REFLEX_RELAY_BRACKET_START" not in line:
            err = self.proc.stderr.read().decode("utf-8", "replace")
            raise RuntimeError(f"reflex-energy didn't start its bracket: {line!r} {err}")

    def stop(self):
        self.proc.stdin.close()
        out = self.proc.stdout.read().decode("utf-8", "replace")
        self.proc.wait()
        return parse_energy(out)


class ReflexLines:
    """Line-delimited JSON over a pair of binary streams (pipe or socket)."""

    def __init__(self, reader, writer):
        self.reader = reader
        self.writer = writer

    def request(self, payload):
        line = (json.dumps(payload) + "\n").encode("utf-8")
        start = time.perf_counter()
        self.writer.write(line)
        self.writer.flush()
        while True:
            raw = self.reader.readline()
            if not raw:
                raise RuntimeError("engine closed the connection mid-request")
            msg = json.loads(raw)
            if msg.get("event") == "final":
                return msg, (time.perf_counter() - start) * 1000.0


def wait_for_ready(proc, marker, timeout_s):
    """Reads the engine's stderr until its READY line; returns the lines seen."""
    seen = []
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        line = proc.stderr.readline()
        if not line:
            break
        line = line.decode("utf-8", "replace").rstrip()
        seen.append(line)
        if marker in line:
            return seen
    raise RuntimeError(
        f"engine never printed {marker} (exit={proc.poll()}):\n" + "\n".join(seen[-20:])
    )


def drain_stderr(proc):
    """Keeps a pipe-full of stderr from blocking the engine during a long run."""
    import threading

    def pump():
        for _ in iter(proc.stderr.readline, b""):
            pass

    threading.Thread(target=pump, daemon=True).start()


def reflex_request(client, payload, allow=()):
    msg, rtt = client.request(dict(payload, timings=True))
    if not msg.get("ok") and msg.get("error_kind") not in allow:
        raise RuntimeError(f"engine error: {msg.get('error_kind')}: {msg.get('error')}")
    return msg, rtt


def parses(text):
    try:
        json.loads(text)
        return True
    except ValueError:
        return False


def reflex_hop(client, system, suffix, max_tokens, prefix_kv, pinned, schema):
    if pinned:
        payload = {"prompt": suffix, "use_pinned": True}
    elif prefix_kv:
        payload = {"prompt": suffix, "import_kv": prefix_kv}
    else:
        payload = {"prompt": system + suffix}
    payload["max_tokens"] = max_tokens
    if schema is not None:
        payload["json_schema"] = schema
    msg, rtt = reflex_request(client, payload, allow=("grammar_dead_end",))
    t = msg.get("timings") or {}
    engine = t.get("parse_ms", 0.0) + t.get("model_ms", 0.0)
    text = msg.get("text", "")
    tokens = len(msg.get("token_ids") or [])
    mask = t.get("mask_ms_total")
    first, model = t.get("first_token_ms"), t.get("model_ms")
    return {
        "rtt_ms": rtt,
        "first_token_ms": first,
        "model_ms": model,
        "decode_ms_per_token": (model - first) / (tokens - 1)
        if first is not None and model is not None and tokens > 1
        else None,
        "overhead_ms": rtt - engine if t else None,
        "kv_io_ms": t.get("kv_io_ms"),
        "mask_ms": mask,
        "mask_ms_per_token": mask / tokens if mask is not None and tokens else None,
        "tokens": tokens,
        "valid": (bool(msg.get("ok")) and parses(text)) if schema is not None else None,
    }, text


def llama_hop(url, prompt, max_tokens, cache_prompt, schema):
    fields = {
        "prompt": prompt,
        "n_predict": max_tokens,
        "temperature": 0.0,
        "top_k": 1,
        "cache_prompt": cache_prompt,
        "stream": False,
    }
    if schema is not None:
        fields["json_schema"] = schema
    body = json.dumps(fields).encode("utf-8")
    req = urllib.request.Request(
        url.rstrip("/") + "/completion",
        data=body,
        headers={"Content-Type": "application/json"},
    )
    start = time.perf_counter()
    with urllib.request.urlopen(req) as resp:
        msg = json.loads(resp.read())
    rtt = (time.perf_counter() - start) * 1000.0
    t = msg.get("timings") or {}
    prompt_ms = t.get("prompt_ms")
    model = (prompt_ms or 0.0) + (t.get("predicted_ms") or 0.0)
    return {
        "rtt_ms": rtt,
        # llama.cpp reports prompt processing separately from decode; prompt_ms
        # plus one decode step is its closest analogue of first_token_ms.
        "first_token_ms": (prompt_ms + t.get("predicted_per_token_ms", 0.0))
        if prompt_ms is not None
        else None,
        "model_ms": model if t else None,
        "overhead_ms": rtt - model if t else None,
        "decode_ms_per_token": t.get("predicted_per_token_ms"),
        "tokens": t.get("predicted_n"),
        "valid": parses(msg.get("content", "")) if schema is not None else None,
    }, msg.get("content", "")


class ColdRunner:
    """Spawns one process per hop, under reflex-energy when `wrap_energy`."""

    def __init__(self, args, wrap_energy):
        self.args = args
        self.wrap_energy = wrap_energy
        self.kv_dir = args.kv_dir or (
            "/dev/shm" if os.path.isdir("/dev/shm") else tempfile.mkdtemp(prefix="reflex-relay-kv-")
        )

    def kv_path(self, name):
        return os.path.join(self.kv_dir, f"relay-{name}-{os.getpid()}.cskv")

    def run(self, cmd, first_output_after=None):
        """(stdout, stderr, wall_ms, first_output_ms, energy dict or None)."""
        if not self.wrap_energy:
            return run_process(cmd, first_output_after) + (None,)
        idle = str(self.args.energy_idle_ms)
        stdout, stderr, _, _ = run_process([self.args.reflex_energy, "--idle-ms", idle, "--"] + cmd)
        # reflex-energy prints its line after the child's output, maybe on the
        # same line if the child's last line had no newline.
        cut = stdout.rfind("REFLEX_ENERGY_OK ")
        if cut < 0:
            raise RuntimeError(f"no REFLEX_ENERGY_OK line in:\n{stdout[-2000:]}")
        energy = parse_energy(stdout[cut:])
        return stdout[:cut], stderr, energy["wall_ms"], None, energy

    def reflex(self, prompt, max_tokens, import_kv=None, export_kv=None):
        """One `reflex generate` process; returns (sample, generated text)."""
        a = self.args
        cmd = [a.reflex, "generate", a.model, prompt]
        if import_kv:
            cmd += ["--import-kv", import_kv]
        if export_kv:
            cmd += ["--export-kv", export_kv]
        else:
            cmd += ["--max-tokens", str(max_tokens)]
        stdout, _, wall, _, energy = self.run(cmd + a.engine_arg)
        f, text = parse_reflex_generate(stdout)
        first = f["process_start_to_first_token_ms"]
        tokens = int(f.get("num_generated", 1))
        sample = {
            "wall_ms": wall,
            "first_token_ms": first,
            "load_ms": f["gguf_open_ms"] + f["cuda_init_ms"] + f["model_load_ms"],
            "prompt_eval_ms": f["prompt_eval_ms"],
            "tokens": tokens,
        }
        last = f.get("process_start_to_last_token_ms")
        if last is not None and tokens > 1:
            sample["decode_ms_per_token"] = (last - first) / (tokens - 1)
        path = import_kv or export_kv
        if path:
            sample["kv_read_ms" if import_kv else "kv_write_ms"] = f.get("kv_io_ms")
            sample["kv_file_mb"] = os.path.getsize(path) / 1e6
        if energy:
            sample.update(energy_sample(energy, 1))
        return sample, text

    def llama_cli(self, prompt, max_tokens, cache_args=()):
        """One `llama-cli` process; returns (sample, generated text)."""
        a = self.args
        cmd = [a.llama_cli, "-m", a.model, "-p", prompt, "-n", str(max_tokens)]
        cmd += ["--temp", "0", "--top-k", "1"] + shlex.split(a.llama_cli_args) + list(cache_args)
        # llama-cli echoes the prompt first, so the first byte past it is the first token.
        stdout, stderr, wall, first, energy = self.run(cmd, len(prompt.encode("utf-8")))
        perf = parse_llama_perf(stderr)
        sample = {"wall_ms": wall, "first_token_ms": first}
        for key in ("load_ms", "prompt_eval_ms"):
            if key in perf:
                sample[key] = perf[key]
        if perf.get("eval_runs"):
            sample["decode_ms_per_token"] = perf["eval_ms"] / perf["eval_runs"]
            sample["tokens"] = int(perf["eval_runs"]) + 1
        if energy:
            sample.update(energy_sample(energy, 1))
        return sample, llama_cli_text(stdout, prompt)


def energy_sample(energy, hops):
    return {
        "energy_j": energy["energy_j"] / hops,
        "energy_net_j": energy["energy_net_j"] / hops,
    }


def run_chain(do_hop, hops, warmup, max_tokens, carry_chars, on_measure_start=None):
    samples = []
    previous = ""
    for hop in range(warmup + hops):
        if hop == warmup and on_measure_start is not None:
            on_measure_start()
        sample, text = do_hop(hop_suffix(hop, previous, carry_chars), max_tokens)
        previous = text.strip()
        if hop >= warmup:
            samples.append(sample)
    return samples


def percentile(values, pct):
    values = sorted(values)
    if not values:
        return None
    k = (len(values) - 1) * pct / 100.0
    lo, hi = int(k), min(int(k) + 1, len(values) - 1)
    return values[lo] + (values[hi] - values[lo]) * (k - lo)


METRICS = (
    ("hop_ms", "hop total (ms)"),
    ("cold_wall_ms", "cold export process (ms)"),
    ("wall_ms", "process wall, spawn to exit (ms)"),
    ("rtt_ms", "round trip (ms)"),
    ("first_token_ms", "first token (ms)"),
    ("load_ms", "load: gguf + cuda init + weights (ms)"),
    ("prompt_eval_ms", "prompt eval to first token (ms)"),
    ("model_ms", "engine total (ms)"),
    ("overhead_ms", "overhead (ms)"),
    ("kv_io_ms", "prefix read/copy (ms)"),
    ("kv_write_ms", "KV file write (ms)"),
    ("kv_read_ms", "KV file read (ms)"),
    ("kv_file_mb", "KV file size (MB)"),
    ("decode_ms_per_token", "decode / token (ms)"),
    ("mask_ms", "json_schema masking (ms)"),
    ("mask_ms_per_token", "masking per token (ms)"),
    ("tokens", "tokens generated"),
    ("energy_j", "GPU energy, gross (J)"),
    ("energy_net_j", "GPU energy, net of idle (J)"),
)


def summarize(samples):
    out = {}
    for key, _ in METRICS:
        vals = [s[key] for s in samples if s.get(key) is not None]
        if vals:
            out[key] = {
                "p50": percentile(vals, 50),
                "p95": percentile(vals, 95),
                "mean": statistics.fmean(vals),
            }
    valid = [s["valid"] for s in samples if s.get("valid") is not None]
    if valid:
        out["valid"] = {"count": sum(valid), "of": len(valid)}
    return out


def print_table(target, summary, n):
    print(f"\n## agent relay: {target}, {n} hops\n")
    print("| metric | p50 | p95 | mean |")
    print("|---|---:|---:|---:|")
    for key, label in METRICS:
        if key in summary:
            s = summary[key]
            d = 3 if key.startswith(("mask", "energy")) else 2
            print(f"| {label} | {s['p50']:.{d}f} | {s['p95']:.{d}f} | {s['mean']:.{d}f} |")
    if "valid" in summary:
        v = summary["valid"]
        print(f"\nvalid JSON outputs: {v['count']}/{v['of']}")


def spawn_reflex(args, extra, subcommand):
    cmd = [args.reflex, subcommand, args.model] + extra + args.engine_arg
    return subprocess.Popen(
        cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE
    )


def selftest():
    """Checks the output parsers against canned lines; no GPU or binaries needed."""
    hop = (
        "REFLEX_PHASE_OK phase=prompt_eval duration_ms=302.500\n"
        "REFLEX_GENERATE_OK process_start_to_first_token_ms=812.500 "
        "process_start_to_last_token_ms=1067.000 gguf_open_ms=10.000 cuda_init_ms=300.000 "
        "model_load_ms=200.000 prompt_eval_ms=302.500 num_generated=32 token_id=7 "
        'token_ids=[7,8] token_text="a \\"q\\" x=1 kv_io_ms=999\\n\\u{200b}\\\\" '
        "weights_dtype=f16 kv_io_ms=104.250\n"
    )
    f, text = parse_reflex_generate(hop)
    assert text == 'a "q" x=1 kv_io_ms=999\n​\\', repr(text)
    assert f["kv_io_ms"] == 104.25 and f["num_generated"] == 32, f
    assert f["process_start_to_first_token_ms"] == 812.5, f

    export = (
        'REFLEX_GENERATE_KV_EXPORT_OK path="/dev/shm/p.cskv" kind=dense seq_len=40 num_layers=28\n'
        "REFLEX_GENERATE_OK process_start_to_first_token_ms=700.000 gguf_open_ms=1.000 "
        "cuda_init_ms=2.000 model_load_ms=3.000 prompt_eval_ms=4.000 token_id=9 "
        'token_text=" The" weights_dtype=f16 kv_io_ms=5.500\n'
    )
    f, text = parse_reflex_generate(export)
    assert text == " The" and f["kv_io_ms"] == 5.5 and "num_generated" not in f, f

    # The format of reflex_engine::energy::ExternalEnergy::report_line.
    energy_line = (
        "REFLEX_ENERGY_OK wall_ms=481.250 window_ms=581.000 energy_mj=25000.0 "
        "idle_power_mw=9000.0 idle_baseline_mj=5229.0 net_energy_mj=19771.0 "
        "method=total_energy_counter exit_code=0\n"
    )
    e = parse_energy(energy_line)
    assert e == {
        "wall_ms": 481.25,
        "energy_j": 25.0,
        "idle_baseline_j": 5.229,
        "energy_net_j": 19.771,
        "idle_power_w": 9.0,
    }, e

    perf = (
        "llama_perf_sampler_print:    sampling time =       3.10 ms /    77 runs\n"
        "llama_perf_context_print:        load time =     412.20 ms\n"
        "llama_perf_context_print: prompt eval time =      20.40 ms /    45 tokens "
        "(    0.45 ms per token,  2205.88 tokens per second)\n"
        "llama_perf_context_print:        eval time =     124.00 ms /    31 runs   "
        "(    4.00 ms per token,   250.00 tokens per second)\n"
        "llama_perf_context_print:       total time =     560.00 ms /    76 tokens\n"
    )
    p = parse_llama_perf(perf)
    assert p == {
        "load_ms": 412.2,
        "prompt_eval_ms": 20.4,
        "prompt_tokens": 45.0,
        "eval_ms": 124.0,
        "eval_runs": 31.0,
    }, p
    assert llama_cli_text("PROMPT note text [end of text]\n\n", "PROMPT") == " note text "

    suffix = hop_suffix(4, "earlier note", 400)
    note, role = split_suffix(suffix)
    assert note + role == suffix and note.endswith("\n") and role.startswith("You are the tester")

    summary = summarize([{"wall_ms": 1.0, "energy_j": 2.0}, {"wall_ms": 3.0, "energy_j": 4.0}])
    assert summary["wall_ms"]["p50"] == 2.0 and summary["energy_j"]["mean"] == 3.0, summary
    print("selftest ok")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        epilog=__doc__.split("\n\n", 1)[1],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument(
        "target",
        choices=list(WARM_TARGETS) + ["cold", "cold-chain", "cold-warm", "llama-cli", "selftest"],
    )
    ap.add_argument("--reflex", default="target/release/reflex")
    ap.add_argument("--model", help="GGUF path (every target but llama-server)")
    ap.add_argument(
        "--engine-arg",
        action="append",
        default=[],
        help="extra argument passed to the reflex subcommand (repeatable)",
    )
    ap.add_argument("--socket", help="UDS path (default: a temp file)")
    ap.add_argument("--url", default="http://127.0.0.1:8080", help="llama-server URL")
    ap.add_argument(
        "--llama-cache-prompt",
        action="store_true",
        help="let llama-server reuse the shared prefix (default off)",
    )
    ap.add_argument(
        "--llama-cli",
        default="llama-cli",
        help="llama.cpp completion binary: llama-cli, or llama-completion on newer builds",
    )
    ap.add_argument(
        "--llama-cli-args",
        default="-ngl 99 --no-warmup -no-cnv --simple-io -c 4096",
        help="extra llama-cli arguments, one shell-quoted string",
    )
    ap.add_argument(
        "--llama-prompt-cache",
        action="store_true",
        help="llama-cli: save the system prompt's state once (--prompt-cache) and reuse it read-only",
    )
    ap.add_argument(
        "--reuse-prefix",
        action="store_true",
        help="stdio/uds: export the system prompt's KV once, import it on every hop",
    )
    ap.add_argument(
        "--pin-prefix",
        action="store_true",
        help="stdio/uds: pin the system prompt's state in VRAM once, resume from it on every hop",
    )
    ap.add_argument(
        "--kv-dir",
        help="where cache files go (default: /dev/shm if present, else a temp dir; tmpfs is best)",
    )
    ap.add_argument("--system-prompt-file", help="shared prefix to use instead of the built-in one")
    ap.add_argument("--json-schema", help="constrain every hop's output to the JSON Schema in this file")
    ap.add_argument(
        "--json-prompt",
        action="store_true",
        help="ask for the note as compact JSON in the shared system prompt",
    )
    ap.add_argument("--energy", action="store_true", help="measure GPU energy with reflex-energy")
    ap.add_argument("--reflex-energy", default="target/release/reflex-energy")
    ap.add_argument(
        "--energy-idle-ms",
        type=int,
        default=2000,
        help="reflex-energy's idle-baseline window before each measurement",
    )
    ap.add_argument("--hops", type=int, default=20)
    ap.add_argument("--warmup", type=int, default=3)
    ap.add_argument("--max-tokens", type=int, default=32)
    ap.add_argument("--carry-chars", type=int, default=400)
    ap.add_argument("--ready-timeout", type=float, default=600.0)
    ap.add_argument("--json-out")
    args = ap.parse_args(argv)
    if args.target == "selftest":
        return selftest()
    if (args.reuse_prefix or args.pin_prefix) and args.target not in ("stdio", "uds"):
        ap.error("--reuse-prefix/--pin-prefix are for stdio/uds; use --llama-cache-prompt")
    if args.reuse_prefix and args.pin_prefix:
        ap.error("pick one of --reuse-prefix and --pin-prefix")
    if args.json_schema and args.target not in WARM_TARGETS:
        ap.error("--json-schema is for stdio/uds/llama-server")
    if args.llama_prompt_cache and args.target != "llama-cli":
        ap.error("--llama-prompt-cache is for llama-cli")
    if args.target != "llama-server" and not args.model:
        ap.error(f"--model is required for {args.target}")
    system = SYSTEM_PROMPT
    if args.system_prompt_file:
        with open(args.system_prompt_file, encoding="utf-8") as f:
            system = f.read()
        if not system.endswith("\n"):
            system += "\n"
    if args.json_prompt:
        system += JSON_NOTE_INSTRUCTION
    schema = None
    if args.json_schema:
        with open(args.json_schema, encoding="utf-8") as f:
            schema = json.load(f)

    cold = None
    if args.target in COLD_TARGETS + ("cold-warm",):
        cold = ColdRunner(args, wrap_energy=args.energy and args.target in COLD_TARGETS)
    bracket = {}

    def start_bracket():
        bracket["running"] = EnergyBracket(args.reflex_energy, args.energy_idle_ms)

    on_measure_start = start_bracket if args.energy and args.target not in COLD_TARGETS else None
    proc = None
    setup = None
    files = []
    try:
        if args.target == "llama-server":

            def do_hop(suffix, max_tokens):
                return llama_hop(
                    args.url, system + suffix, max_tokens, args.llama_cache_prompt, schema
                )

        elif args.target == "cold":

            def do_hop(suffix, max_tokens):
                return cold.reflex(system + suffix, max_tokens)

        elif args.target == "cold-chain":
            prefix_kv = cold.kv_path("prefix")
            files.append(prefix_kv)
            setup, _ = cold.reflex(system, 1, export_kv=prefix_kv)
            print(
                f"cold export of the prefix: {setup['wall_ms']:.1f} ms wall, "
                f"{setup['kv_write_ms']:.1f} ms write, {setup['kv_file_mb']:.1f} MB -> {prefix_kv}",
                file=sys.stderr,
            )

            def do_hop(suffix, max_tokens):
                return cold.reflex(suffix, max_tokens, import_kv=prefix_kv)

        elif args.target == "llama-cli":
            cache_args = ()
            if args.llama_prompt_cache:
                cache = os.path.join(cold.kv_dir, f"relay-llama-prompt-cache-{os.getpid()}.bin")
                files.append(cache)
                setup, _ = cold.llama_cli(system, 1, ["--prompt-cache", cache])
                setup["kv_file_mb"] = os.path.getsize(cache) / 1e6
                print(
                    f"llama-cli prompt cache: {setup['wall_ms']:.1f} ms wall, "
                    f"{setup['kv_file_mb']:.1f} MB -> {cache}",
                    file=sys.stderr,
                )
                cache_args = ("--prompt-cache", cache, "--prompt-cache-ro")

            def do_hop(suffix, max_tokens):
                return cold.llama_cli(system + suffix, max_tokens, cache_args)

        else:
            if args.target == "uds":
                if not hasattr(socket, "AF_UNIX"):
                    ap.error("uds needs a platform with AF_UNIX sockets; use stdio")
                sock_path = args.socket or os.path.join(
                    tempfile.mkdtemp(prefix="reflex-relay-"), "reflex.sock"
                )
                proc = spawn_reflex(args, [sock_path], "uds")
                wait_for_ready(proc, "REFLEX_UDS_READY", args.ready_timeout)
                drain_stderr(proc)
                conn = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                conn.connect(sock_path)
                client = ReflexLines(conn.makefile("rb"), conn.makefile("wb"))
            else:
                proc = spawn_reflex(args, [], "stdio")
                wait_for_ready(proc, "REFLEX_STDIO_READY", args.ready_timeout)
                drain_stderr(proc)
                client = ReflexLines(proc.stdout, proc.stdin)

            prefix_kv = None
            if args.reuse_prefix:
                prefix_kv = os.path.join(
                    args.kv_dir or tempfile.mkdtemp(prefix="reflex-relay-kv-"),
                    f"relay-prefix-{os.getpid()}.cskv",
                )
                files.append(prefix_kv)
                msg, _ = reflex_request(
                    client, {"prompt": system, "export_kv": prefix_kv, "max_tokens": 1}
                )
                print(
                    f"exported prefix KV ({os.path.getsize(prefix_kv)} bytes) in "
                    f"{msg['timings']['model_ms']:.1f} ms -> {prefix_kv}",
                    file=sys.stderr,
                )

            if args.pin_prefix:
                msg, _ = reflex_request(
                    client, {"prompt": system, "pin_prefix": True, "max_tokens": 1}
                )
                print(
                    f"pinned prefix in {msg['timings']['model_ms']:.1f} ms",
                    file=sys.stderr,
                )

            if args.target == "cold-warm":
                hop_kv = cold.kv_path("hop")
                files.append(hop_kv)

                def do_hop(suffix, max_tokens):
                    note, role = split_suffix(suffix)
                    c, _ = cold.reflex(system + note, 1, export_kv=hop_kv)
                    w, text = reflex_hop(client, system, role, max_tokens, hop_kv, False, None)
                    os.remove(hop_kv)
                    return {
                        "hop_ms": c["wall_ms"] + w["rtt_ms"],
                        "cold_wall_ms": c["wall_ms"],
                        "kv_write_ms": c["kv_write_ms"],
                        "kv_file_mb": c["kv_file_mb"],
                        "rtt_ms": w["rtt_ms"],
                        "first_token_ms": w["first_token_ms"],
                        "kv_read_ms": w["kv_io_ms"],
                        "model_ms": w["model_ms"],
                        "decode_ms_per_token": w.get("decode_ms_per_token"),
                        "tokens": w["tokens"],
                    }, text

            else:

                def do_hop(suffix, max_tokens):
                    return reflex_hop(
                        client, system, suffix, max_tokens, prefix_kv, args.pin_prefix, schema
                    )

        samples = run_chain(
            do_hop, args.hops, args.warmup, args.max_tokens, args.carry_chars, on_measure_start
        )
        energy_bracket = None
        if "running" in bracket:
            energy_bracket = bracket.pop("running").stop()
            energy_bracket.update(energy_sample(energy_bracket, len(samples)))
    finally:
        if "running" in bracket:
            bracket["running"].proc.kill()
        if proc is not None:
            proc.kill()
            proc.wait()
        for path in files:
            if os.path.exists(path):
                os.remove(path)

    summary = summarize(samples)
    label = args.target + (
        ", prefix reused" if args.reuse_prefix else ", prefix pinned" if args.pin_prefix else ""
    ) + (", prompt cache" if args.llama_prompt_cache else "") + (
        ", json_schema" if schema is not None else ""
    )
    print_table(label, summary, len(samples))
    if setup is not None:
        print("\nsetup (one cold process): " + ", ".join(f"{k}={v:.2f}" for k, v in setup.items()))
    if energy_bracket is not None:
        print(
            f"\nenergy over the measured hops (one bracket): "
            f"{energy_bracket['energy_j']:.3f} J/hop gross, "
            f"{energy_bracket['energy_net_j']:.3f} J/hop net of idle "
            f"({energy_bracket['idle_power_w']:.1f} W idle, {energy_bracket['wall_ms']:.0f} ms window)"
        )
    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "target": args.target,
                    "model": args.model,
                    "hops": args.hops,
                    "warmup": args.warmup,
                    "max_tokens": args.max_tokens,
                    "carry_chars": args.carry_chars,
                    "llama_cache_prompt": args.llama_cache_prompt,
                    "llama_cli_args": args.llama_cli_args if args.target == "llama-cli" else None,
                    "llama_prompt_cache": args.llama_prompt_cache,
                    "reuse_prefix": args.reuse_prefix,
                    "pin_prefix": args.pin_prefix,
                    "kv_dir": cold.kv_dir if cold is not None else args.kv_dir,
                    "json_schema": args.json_schema,
                    "json_prompt": args.json_prompt,
                    "energy": args.energy,
                    "energy_idle_ms": args.energy_idle_ms if args.energy else None,
                    "system_prompt_chars": len(system),
                    "setup": setup,
                    "energy_bracket": energy_bracket,
                    "summary": summary,
                    "samples": samples,
                },
                f,
                indent=2,
            )
    return 0


if __name__ == "__main__":
    sys.exit(main())
