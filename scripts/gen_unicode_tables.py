#!/usr/bin/env python3
"""Generates src/tokenizer_unicode.rs from llama.cpp's src/unicode-data.cpp.

The pre-tokenizer split regexes of the gpt2-model GGUF tokenizers use Unicode
categories (\\p{L}, \\p{N}, \\p{M}, \\p{P}, \\p{S}) and llama.cpp's own
whitespace set. Rust's std can't answer \\p{P}/\\p{S}/\\p{M}, and its
`is_alphabetic`/`is_whitespace` aren't the same sets, so the ported splitters
(src/tokenizer.rs, see docs/design/tokenizer-pre-types.md) read llama.cpp's
tables instead: one category per codepoint range (`unicode_ranges_flags`) and
`unicode_set_whitespace`, transcribed mechanically so they can't drift by hand.

Pinned to llama.cpp 79e2e74, the commit every reference build in this repo uses.
Run from the repo root: `python3 scripts/gen_unicode_tables.py [path/to/unicode-data.cpp]`
(downloads the pinned file when no path is given).
"""

import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "79e2e74"
URL = f"https://raw.githubusercontent.com/ggml-org/llama.cpp/{COMMIT}/src/unicode-data.cpp"
REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_RS = REPO_ROOT / "src" / "tokenizer_unicode.rs"


def main() -> None:
    if len(sys.argv) > 1:
        src = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        src = urllib.request.urlopen(URL).read().decode("utf-8")

    ranges_body = re.search(
        r"unicode_ranges_flags = \{[^\n]*\n(.*?)\n\};", src, re.S
    ).group(1)
    ranges = [
        (int(a, 16), int(b, 16))
        for a, b in re.findall(r"\{0x([0-9A-F]+), 0x([0-9A-F]+)\}", ranges_body)
    ]
    assert ranges[0][0] == 0 and ranges[-1][0] == 0x110000
    # Every flag in this table is a single category bit (no helper bits), so it
    # fits a u8. Merge neighbours with the same category to shrink the table.
    merged = []
    for start, flags in ranges:
        assert flags <= 0xFF, hex(flags)
        if merged and merged[-1][1] == flags:
            continue
        merged.append((start, flags))

    ws_body = re.search(
        r"unicode_set_whitespace = \{\n(.*?)\n\};", src, re.S
    ).group(1)
    whitespace = sorted(int(x, 16) for x in re.findall(r"0x([0-9A-F]+)", ws_body))

    out = []
    out.append(
        "//! Unicode tables for the gpt2-model pre-tokenizers, generated by\n"
        "//! `scripts/gen_unicode_tables.py` from llama.cpp's `src/unicode-data.cpp`\n"
        f"//! at `{COMMIT}`. Do not edit by hand; rerun the script.\n"
        "//!\n"
        "//! [`CATEGORY_RANGES`]: `(first codepoint, category flag)`, sorted, each range\n"
        "//! running to the next entry's start; the last entry is the `0x110000`\n"
        "//! sentinel. Flags are llama.cpp's `unicode_cpt_flags` category bits.\n"
        "//! [`WHITESPACE`]: llama.cpp's `unicode_set_whitespace`, sorted.\n"
        "\n"
        "// The full flag set mirrors `unicode_cpt_flags`, used or not.\n"
        "#![allow(dead_code)]\n"
        "\n"
        "pub(crate) const UNDEFINED: u8 = 0x01;\n"
        "pub(crate) const NUMBER: u8 = 0x02;\n"
        "pub(crate) const LETTER: u8 = 0x04;\n"
        "pub(crate) const SEPARATOR: u8 = 0x08;\n"
        "pub(crate) const ACCENT_MARK: u8 = 0x10;\n"
        "pub(crate) const PUNCTUATION: u8 = 0x20;\n"
        "pub(crate) const SYMBOL: u8 = 0x40;\n"
        "pub(crate) const CONTROL: u8 = 0x80;\n"
        "\n"
        "#[rustfmt::skip]\n"
        "pub(crate) const CATEGORY_RANGES: &[(u32, u8)] = &[\n"
    )
    line = []
    for start, flags in merged:
        line.append(f"(0x{start:06X}, 0x{flags:02X}),")
        if len(line) == 6:
            out.append("    " + " ".join(line) + "\n")
            line = []
    if line:
        out.append("    " + " ".join(line) + "\n")
    out.append("];\n\n")
    out.append("#[rustfmt::skip]\npub(crate) const WHITESPACE: &[u32] = &[\n")
    out.append("    " + " ".join(f"0x{c:04X}," for c in whitespace) + "\n];\n")

    OUT_RS.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT_RS} ({len(merged)} ranges, {len(whitespace)} whitespace)")


if __name__ == "__main__":
    main()
